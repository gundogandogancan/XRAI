// Portable, end-to-end encrypted backup contract (P02 decisions 3–4; hardening V32-02-01H §1, §5).
//
// Format v2 — "sealed backup": a versioned OUTER AEAD envelope.
//   cleartext: magic, format version, salt(16), nonce(12)            ← technical header only
//   ciphertext: BackupBody = createdAt + [RecordEnvelope], block-padded ← ALL record metadata inside
//   tag(16)                                                          ← AES-256-GCM over body, AAD = header
// Record ids, classes, tiers, timestamps and the record count are never visible outside the ciphertext.
// Size leakage: the padded ciphertext length still reveals the approximate total size (4 KiB granularity).

/// 256-bit user recovery key. Generated by the adapter from the system CSPRNG; shown to the user
/// once; never stored by XRAI. Its description is redacted.
public struct RecoveryKey: Hashable, Sendable {
    public static let byteCount = 32
    public let bytes: [UInt8]

    public init(bytes: [UInt8]) throws {
        guard bytes.count == RecoveryKey.byteCount else {
            throw VaultError.recoveryKeyInvalid(reason: "expected \(RecoveryKey.byteCount) bytes, got \(bytes.count)")
        }
        guard bytes.contains(where: { $0 != 0 }) else { throw VaultError.recoveryKeyInvalid(reason: "all-zero key") }
        self.bytes = bytes
    }

    /// Hex in groups of 8 characters for human transcription. Display only.
    public var displayGroups: [String] {
        let hex = RecordID.hexString(bytes)
        var out: [String] = []
        var i = hex.startIndex
        while i < hex.endIndex {
            let j = hex.index(i, offsetBy: 8, limitedBy: hex.endIndex) ?? hex.endIndex
            out.append(String(hex[i..<j]))
            i = j
        }
        return out
    }

    /// Parses the grouped hex form (spaces/dashes ignored).
    public static func parse(display: String) throws -> RecoveryKey {
        let cleaned = display.filter { $0 != " " && $0 != "-" }.lowercased()
        guard cleaned.count == RecoveryKey.byteCount * 2 else { throw VaultError.recoveryKeyInvalid(reason: "wrong length") }
        var out: [UInt8] = []
        var chars = Array(cleaned)
        while !chars.isEmpty {
            let pair = String(chars[0...1])
            chars.removeFirst(2)
            guard let v = UInt8(pair, radix: 16) else { throw VaultError.recoveryKeyInvalid(reason: "non-hex character") }
            out.append(v)
        }
        return try RecoveryKey(bytes: out)
    }
}

extension RecoveryKey: CustomStringConvertible, CustomDebugStringConvertible {
    public var description: String { "RecoveryKey(redacted)" }
    public var debugDescription: String { "RecoveryKey(redacted)" }
}

/// Resource limits enforced on import (and on export for symmetry). Fail closed.
public enum BackupLimits {
    public static let maxBackupBytes = 256 * 1024 * 1024
    public static let maxEntries = 100_000
    public static let maxRecordCiphertextBytes = 64 * 1024 * 1024
    public static let maxNonceBytes = 12
    public static let maxTagBytes = 16
    public static let maxWrappedKeyBytes = 32
    public static let paddingBlockBytes = 4096
}

/// Encrypted body of a sealed backup. Every personal metadata field lives here.
public struct BackupBody: Hashable, Sendable {
    public let createdAtUnixSeconds: Int64
    public let entries: [RecordEnvelope]

    public init(createdAtUnixSeconds: Int64, entries: [RecordEnvelope]) {
        self.createdAtUnixSeconds = createdAtUnixSeconds
        self.entries = entries
    }

    public func encode() -> [UInt8] {
        var e = CanonicalEncoder()
        e.appendI64(createdAtUnixSeconds)
        e.appendU32(UInt32(entries.count))
        for env in entries { env.encode(into: &e) }
        return e.bytes
    }

    /// Decodes with limits: entry count, per-field lengths, duplicate record ids, trailing bytes.
    /// Every header is validated (version, algorithm, tier floor) during decoding.
    public static func decode(_ bytes: [UInt8]) throws -> BackupBody {
        var d = CanonicalDecoder(bytes)
        let t = try d.readI64()
        let n = Int(try d.readU32())
        guard n <= BackupLimits.maxEntries else { throw VaultError.limitExceeded("entry count") }
        var entries: [RecordEnvelope] = []
        entries.reserveCapacity(min(n, 1024))
        var seen = Set<String>()
        for _ in 0..<n {
            let env = try RecordEnvelope.decode(from: &d)
            try BackupBody.validateLimits(env)
            guard env.wrappedDEK.boundRecordID == env.header.recordID else { throw VaultError.backupCorrupted(reason: "record binding") }
            guard seen.insert(env.header.recordID.hex).inserted else { throw VaultError.duplicateRecordID }
            entries.append(env)
        }
        guard d.isAtEnd else { throw VaultError.backupCorrupted(reason: "trailing bytes") }
        return BackupBody(createdAtUnixSeconds: t, entries: entries)
    }

    public static func validateLimits(_ env: RecordEnvelope) throws {
        guard env.nonce.count == BackupLimits.maxNonceBytes else { throw VaultError.invalidLength(field: "nonce", expected: BackupLimits.maxNonceBytes, actual: env.nonce.count) }
        guard env.tag.count == BackupLimits.maxTagBytes else { throw VaultError.invalidLength(field: "tag", expected: BackupLimits.maxTagBytes, actual: env.tag.count) }
        guard env.ciphertext.count <= BackupLimits.maxRecordCiphertextBytes else { throw VaultError.limitExceeded("record ciphertext") }
        guard env.wrappedDEK.nonce.count == BackupLimits.maxNonceBytes else { throw VaultError.invalidLength(field: "wrap nonce", expected: BackupLimits.maxNonceBytes, actual: env.wrappedDEK.nonce.count) }
        guard env.wrappedDEK.tag.count == BackupLimits.maxTagBytes else { throw VaultError.invalidLength(field: "wrap tag", expected: BackupLimits.maxTagBytes, actual: env.wrappedDEK.tag.count) }
        guard env.wrappedDEK.ciphertext.count == BackupLimits.maxWrappedKeyBytes else { throw VaultError.invalidLength(field: "wrapped key", expected: BackupLimits.maxWrappedKeyBytes, actual: env.wrappedDEK.ciphertext.count) }
    }

    /// Length-prefixed body padded with zeros to a multiple of the padding block.
    public static func pad(_ body: [UInt8]) -> [UInt8] {
        var e = CanonicalEncoder()
        e.appendU32(UInt32(body.count))
        var out = e.bytes + body
        let block = BackupLimits.paddingBlockBytes
        let rem = out.count % block
        if rem != 0 { out += [UInt8](repeating: 0, count: block - rem) }
        return out
    }

    public static func unpad(_ padded: [UInt8]) throws -> [UInt8] {
        var d = CanonicalDecoder(padded)
        let n = Int(try d.readU32())
        guard n <= padded.count - 4 else { throw VaultError.backupCorrupted(reason: "padding length") }
        let body = Array(padded[4..<4 + n])
        for b in padded[(4 + n)...] where b != 0 { throw VaultError.backupCorrupted(reason: "padding bytes") }
        return body
    }
}

/// The sealed backup file. Only technical fields are in the clear.
public struct SealedBackup: Hashable, Sendable {
    public static let magic: [UInt8] = Array("XRAIBK".utf8)
    public static let currentFormatVersion: UInt16 = 2
    public static let saltBytes = 16
    public static let backupKeyID = "backup"

    public let formatVersion: UInt16
    public let salt: [UInt8]
    public let nonce: [UInt8]
    public let ciphertext: [UInt8]
    public let tag: [UInt8]

    public init(formatVersion: UInt16 = SealedBackup.currentFormatVersion, salt: [UInt8], nonce: [UInt8], ciphertext: [UInt8], tag: [UInt8]) {
        self.formatVersion = formatVersion
        self.salt = salt
        self.nonce = nonce
        self.ciphertext = ciphertext
        self.tag = tag
    }

    /// AEAD associated data: the technical header, so version/salt/nonce cannot be swapped.
    public static func associatedData(formatVersion: UInt16, salt: [UInt8], nonce: [UInt8]) -> [UInt8] {
        var e = CanonicalEncoder()
        for b in magic { e.appendU8(b) }
        e.appendU16(formatVersion)
        e.appendBytes(salt)
        e.appendBytes(nonce)
        return e.bytes
    }

    public var associatedData: [UInt8] { SealedBackup.associatedData(formatVersion: formatVersion, salt: salt, nonce: nonce) }

    public func encode() -> [UInt8] {
        var e = CanonicalEncoder()
        for b in SealedBackup.magic { e.appendU8(b) }
        e.appendU16(formatVersion)
        e.appendBytes(salt)
        e.appendBytes(nonce)
        e.appendBytes(ciphertext)
        e.appendBytes(tag)
        return e.bytes
    }

    /// Strict decode: size limit, magic, supported version, field lengths, no trailing bytes.
    public static func decode(_ bytes: [UInt8]) throws -> SealedBackup {
        guard bytes.count <= BackupLimits.maxBackupBytes else { throw VaultError.limitExceeded("backup size") }
        var d = CanonicalDecoder(bytes)
        for expected in magic {
            guard try d.readU8() == expected else { throw VaultError.backupCorrupted(reason: "bad magic") }
        }
        let v = try d.readU16()
        guard v == currentFormatVersion else { throw VaultError.unsupportedFormat(v) }
        let salt = try d.readBytes()
        guard salt.count == saltBytes else { throw VaultError.invalidLength(field: "salt", expected: saltBytes, actual: salt.count) }
        let nonce = try d.readBytes()
        guard nonce.count == BackupLimits.maxNonceBytes else { throw VaultError.invalidLength(field: "nonce", expected: BackupLimits.maxNonceBytes, actual: nonce.count) }
        let ct = try d.readBytes()
        let tag = try d.readBytes()
        guard tag.count == BackupLimits.maxTagBytes else { throw VaultError.invalidLength(field: "tag", expected: BackupLimits.maxTagBytes, actual: tag.count) }
        guard d.isAtEnd else { throw VaultError.backupCorrupted(reason: "trailing bytes") }
        return SealedBackup(formatVersion: v, salt: salt, nonce: nonce, ciphertext: ct, tag: tag)
    }
}

extension SealedBackup: CustomStringConvertible {
    public var description: String { "SealedBackup(v" + String(formatVersion) + ", bytes: " + String(ciphertext.count) + ", body: <encrypted>)" }
}
